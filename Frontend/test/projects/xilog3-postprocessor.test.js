import { describe, expect, it } from "vitest";

import {
    AVAILABLE_POSTPROCESSORS,
    createPluginConfiguration,
    DEFAULT_MACHINING_ASSIGNMENTS,
    MACHINING_INTENT_IDS,
    MACHINING_KINDS,
    generateCncMachineCode as generateMachineCode
} from "@Engine/postprocessor/index.js";
import { getPartMachineCodeFaces } from "../../src/features/projects/cnc/shared/machineCodeFaces.js";

const withNeutralCnc = part => ({
    ...part,
    CNC: {
        version: 2,
        coordinateSystem: {
            unit: "mm",
            origin: "top-left",
            xAxis: "right",
            yAxis: "down",
            depthDirection: "into-material"
        },
        ...(part?.CNC ?? {})
    }
});

const generateCncMachineCode = (postprocessor, payload) => generateMachineCode(postprocessor, {
    assignments: DEFAULT_MACHINING_ASSIGNMENTS,
    ...payload,
    part: withNeutralCnc(payload.part)
});

const descriptor = AVAILABLE_POSTPROCESSORS.find(item => item.id === "scm-xilog3-routolink");
const instance = {
    id: "wiest-routolink",
    pluginId: descriptor.id,
    name: "SCM RoutoLink",
    configuration: createPluginConfiguration({ manifest: descriptor })
};

describe("SCM Xilog 3 postprocessor", () => {
    it("publishes the workshop-specific XXL adapter", () => {
        expect(descriptor).toMatchObject({
            version: "0.5.0",
            sourceFormat: "Xilog 3 XXL (ASCII, CRLF)",
            machineCodeFaces: ["A", "B"],
            capabilities: {
                viewer: true,
                machineCode: true,
                machiningResolution: true
            }
        });
        expect(descriptor.machiningLocations.map(location => location.id)).toEqual(["A", "AB", "AD", "DA", "DB", "D"]);
        expect(instance.configuration).toMatchObject({
            workingFields: "AD",
            departurePositionA: 1600,
            departurePositionAD: 2800,
            toolSetup: "W",
            flipYAxis: true,
            grooveTool: 81,
            millingTool: 114
        });
    });

    it("generates a CRLF XXL program using commands verified in the Xilog runtime", () => {
        const result = generateCncMachineCode(instance, {
            fileName: "seite-links",
            part: {
                PID: "part-1",
                L: 450,
                B: 695,
                T: 20,
                CNC: {
                    operations: [
                        { id: "drill", kind: MACHINING_KINDS.DRILL_PATTERN, intentId: MACHINING_INTENT_IDS.JOINT_CONNECTOR, face: "A", x: 100, y: 100, depth: 8, diameter: 5, count: 2, stepX: 32, stepY: 0 },
                        { id: "shelf", kind: MACHINING_KINDS.DRILL_ROW, intentId: MACHINING_INTENT_IDS.SHELF_PIN_ROW, face: "A", start: 20, end: 116, spacing: 32, crossPositions: [37, 658], depth: 12, diameter: 5 },
                        { id: "groove", kind: MACHINING_KINDS.MILL_GROOVE, intentId: MACHINING_INTENT_IDS.BACK_GROOVE, face: "A", start: { x: -20, y: 685, z: 9 }, end: { x: 470, y: 685, z: 9 }, width: 8.3 },
                        { id: "mill-start", kind: MACHINING_KINDS.MILL_PATH, intentId: MACHINING_INTENT_IDS.BACK_RABBET, motion: "rapid", face: "A", target: { x: -20, y: 688, z: 15 } },
                        { id: "mill-line", kind: MACHINING_KINDS.MILL_PATH, intentId: MACHINING_INTENT_IDS.BACK_RABBET, motion: "linear", face: "A", target: { x: 470, y: 688, z: 15 } }
                    ]
                }
            }
        });

        expect(result.supported).toBe(true);
        expect(result.fileName).toBe("SEITE-LI.xxl");
        expect(result.encoding).toBe("windows-1252");
        expect(result.code).toBe([
            'H DX=450 DY=695 DZ=20 -AD C=0 T=0 R=99 *MM /"W" ;Generated by CarpentersProduction - validate in Xilog 3',
            'XBO X=100 Y=595 Z=8 R=2 x=32 D=5 N="P"',
            'LR2 X=20 Y=37 Z=12 x=334 y=37 C=0 P=0',
            'RNT X=-20 Y=10 Z=9 x=470 B=8.3 T=81 C=3',
            'C=0',
            'XG0 X=-20 Y=7 Z=15 T=114',
            'XL2P X=470 Y=7 Z=15',
            'N X=2800',
            ""
        ].join("\r\n"));
        expect(result.metadata.departure).toEqual({ field: "AD", position: 2800 });
        expect(result.diagnostics).toContainEqual(expect.objectContaining({
            level: "warning",
            code: "XILOG3_IMPORT_VALIDATION_REQUIRED"
        }));
    });

    it("generates a separate XXL program for machining side B", () => {
        const operation = (id, face, x, y) => ({
            id,
            kind: MACHINING_KINDS.DRILL_POINT,
            intentId: MACHINING_INTENT_IDS.MANUAL_DRILLING,
            face,
            x,
            y,
            depth: 8,
            diameter: 5
        });
        const part = {
            PID: "seite-links",
            L: 450,
            B: 695,
            T: 20,
            CNC: {
                operations: [
                    operation("face-a", "A", 10, 20),
                    operation("face-b", "B", 30, 40),
                    operation("both", "both", 50, 60)
                ]
            }
        };

        const sideA = generateCncMachineCode(instance, { part, fileName: "seite-links", face: "A" });
        const sideB = generateCncMachineCode(instance, { part, fileName: "seite-links", face: "B" });

        expect(sideA.supported).toBe(true);
        expect(sideA.fileName).toBe("SEITE-LI.xxl");
        expect(sideA.metadata).toMatchObject({ programFace: "A", operationCount: 2 });
        expect(sideA.code).toContain('XBO X=10 Y=675 Z=8 R=1 D=5 N="P"');
        expect(sideA.code).toContain('XBO X=50 Y=635 Z=8 R=1 D=5 N="P"');
        expect(sideA.code).not.toContain("XBO X=30 ");

        expect(sideB.supported).toBe(true);
        expect(sideB.fileName).toBe("SEITE_B.xxl");
        expect(sideB.metadata).toMatchObject({ programFace: "B", operationCount: 2 });
        expect(sideB.code).toContain("validate in Xilog 3 - face B");
        expect(sideB.code).toContain('XBO X=30 Y=655 Z=8 R=1 D=5 N="P"');
        expect(sideB.code).toContain('XBO X=50 Y=635 Z=8 R=1 D=5 N="P"');
        expect(sideB.code).not.toContain("XBO X=10 ");
        expect(getPartMachineCodeFaces(part, descriptor)).toEqual(["A", "B"]);
    });

    it("does not add an empty side-B export when a part has no B machining", () => {
        expect(getPartMachineCodeFaces({
            CNC: { operations: [{ face: "A" }] }
        }, descriptor)).toEqual(["A"]);
    });

    it("adds the configured field A departure step as the final program command", () => {
        const result = generateCncMachineCode({
            ...instance,
            configuration: {
                ...instance.configuration,
                workingFields: "A",
                departurePositionA: 1600
            }
        }, {
            part: {
                PID: "FIELD-A",
                L: 450,
                B: 695,
                T: 20,
                CNC: { operations: [] }
            }
        });

        expect(result.code).toBe([
            'H DX=450 DY=695 DZ=20 -A C=0 T=0 R=99 *MM /"W" ;Generated by CarpentersProduction - validate in Xilog 3',
            "N X=1600",
            ""
        ].join("\r\n"));
        expect(result.metadata.departure).toEqual({ field: "A", position: 1600 });
    });

    it("uses LR2M with the original limits for a centered 32 mm shelf row", () => {
        const result = generateCncMachineCode(instance, {
            part: {
                PID: "SHELF-CENTERED",
                L: 450,
                B: 695,
                T: 20,
                CNC: { operations: [{
                    id: "shelf-centered",
                    kind: MACHINING_KINDS.DRILL_ROW,
                    intentId: MACHINING_INTENT_IDS.SHELF_PIN_ROW,
                    face: "A",
                    start: 111,
                    end: 239,
                    rangeStart: 100,
                    rangeEnd: 250,
                    centered: true,
                    spacing: 32,
                    crossPositions: [60, 635],
                    depth: 16,
                    diameter: 5
                }] }
            }
        });

        expect(result.code).toContain("LR2M X=100 Y=60 Z=16 x=200 y=60");
        expect(result.code).not.toContain("LR2M X=100 Y=60 Z=16 x=200 y=60 C=0");
    });

    it("writes only additional SX and SY mirrors after the header", () => {
        const result = generateCncMachineCode(instance, {
            part: {
                PID: "MIRROR",
                L: 450,
                B: 695,
                T: 20,
                CNC: {
                    header: { stopId: "D", edgeAtStop: "back", sx: true, sy: true, comment: "Rueckseite" },
                    operations: []
                }
            }
        });

        expect(result.code.split("\r\n").slice(0, 3)).toEqual([
            expect.stringContaining("-D"),
            "SX=1",
            "SY=1"
        ]);
        expect(result.code).toContain("Rueckseite");
        expect(result.metadata.header).toMatchObject({
            machineMirrorX: true,
            machineMirrorY: true,
            displayMirrorX: false,
            displayMirrorY: false
        });
    });

    it("uses an administrator-defined departure position", () => {
        const result = generateCncMachineCode({
            ...instance,
            configuration: {
                ...instance.configuration,
                departurePositionAD: 2950
            }
        }, {
            part: {
                PID: "CUSTOM-DEPARTURE",
                L: 450,
                B: 695,
                T: 20,
                CNC: { operations: [] }
            }
        });

        expect(result.code.endsWith("N X=2950\r\n")).toBe(true);
        expect(result.metadata.departure).toEqual({ field: "AD", position: 2950 });
    });

    it("uses the installed VBH cycle for horizontal connector drilling", () => {
        const result = generateCncMachineCode(instance, {
            part: {
                PID: "VBH-1",
                L: 450,
                B: 695,
                T: 20,
                CNC: {
                    operations: [{
                        id: "horizontal",
                        kind: MACHINING_KINDS.DRILL_EDGE_PATTERN,
                        intentId: MACHINING_INTENT_IDS.JOINT_CONNECTOR,
                        face: "A",
                        edge: "right",
                        positions: [50, 248, 446, 645],
                        spacing: 198,
                        depth: 28,
                        diameter: 8
                    }]
                }
            }
        });

        expect(result.code).toContain("F=2\r\nVBH X=10 Y=50 y=50 Z=28 R=198 D=8\r\nF=1");
    });

    it("switches directly between consecutive VBH side faces without an intermediate F=1", () => {
        const operation = edge => ({
            id: `horizontal-${edge}`,
            kind: MACHINING_KINDS.DRILL_EDGE_PATTERN,
            intentId: MACHINING_INTENT_IDS.JOINT_CONNECTOR,
            face: "A",
            edge,
            positions: [50, 248, 446, 645],
            spacing: 198,
            depth: 28,
            diameter: 8
        });
        const result = generateCncMachineCode(instance, {
            part: {
                PID: "VBH-SIDES",
                L: 450,
                B: 695,
                T: 20,
                CNC: { operations: [operation("left"), operation("right")] }
            }
        });

        expect(result.code).toContain([
            "F=3",
            "VBH X=10 Y=50 y=50 Z=28 R=198 D=8",
            "F=2",
            "VBH X=10 Y=50 y=50 Z=28 R=198 D=8",
            "F=1",
            "N X=2800"
        ].join("\r\n"));
        expect(result.code).not.toContain("VBH X=10 Y=50 y=50 Z=28 R=198 D=8\r\nF=1\r\nF=2");
    });

    it("always emits RNT with C=3 even if an obsolete configuration contains another value", () => {
        const result = generateCncMachineCode({
            ...instance,
            configuration: { ...instance.configuration, grooveCorrection: 0 }
        }, {
            part: {
                PID: "RNT-CORRECTION",
                L: 450,
                B: 695,
                T: 20,
                CNC: { operations: [{
                    id: "groove",
                    kind: MACHINING_KINDS.MILL_GROOVE,
                    intentId: MACHINING_INTENT_IDS.BACK_GROOVE,
                    face: "A",
                    start: { x: 3, y: 20, z: 9 },
                    end: { x: 447, y: 20, z: 9 },
                    width: 8.3
                }] }
            }
        });

        expect(result.code).toContain("RNT X=3 Y=675 Z=9 x=447 B=8.3 T=81 C=3");
    });

    it("translates the VB operation shape emitted by the cabinet compiler", () => {
        const result = generateCncMachineCode(instance, {
            part: {
                PID: "VB-1",
                L: 450,
                B: 695,
                T: 20,
                CNC: {
                    operations: [{
                        id: "vertical-row",
                        kind: MACHINING_KINDS.DRILL_LINEAR_PATTERN,
                        intentId: MACHINING_INTENT_IDS.JOINT_CONNECTOR,
                        face: "A",
                        x: 120,
                        y: 50,
                        count: 4,
                        spacing: 198,
                        depth: 15,
                        diameter: 8
                    }]
                }
            }
        });

        expect(result.code).toContain("VB1 X=120 Y=50 y=51 Z=15 R=198 D=8");
    });

    it("keeps a generic manual linear drilling pattern as XBO instead of a connector macro", () => {
        const result = generateCncMachineCode({
            ...instance,
            configuration: { ...instance.configuration, flipYAxis: false }
        }, {
            part: {
                PID: "MANUAL-ROW",
                L: 450,
                B: 695,
                T: 20,
                CNC: { operations: [{
                    id: "manual-row",
                    kind: MACHINING_KINDS.DRILL_LINEAR_PATTERN,
                    intentId: MACHINING_INTENT_IDS.MANUAL_DRILLING,
                    face: "A",
                    x: 120,
                    y: 50,
                    count: 4,
                    spacing: 198,
                    depth: 15,
                    diameter: 8
                }] }
            }
        });

        expect(result.code).toContain('XBO X=120 Y=50 Z=15 R=4 y=198 D=8 N="P"');
        expect(result.code).not.toContain("\r\nVB1 ");
    });

    it("exports a two-dimensional manual drilling grid as one XBO row per grid row", () => {
        const result = generateCncMachineCode({
            ...instance,
            configuration: { ...instance.configuration, flipYAxis: false }
        }, {
            part: {
                PID: "GRID-1",
                L: 450,
                B: 695,
                T: 20,
                CNC: { operations: [{
                    id: "grid",
                    kind: MACHINING_KINDS.DRILL_PATTERN,
                    intentId: MACHINING_INTENT_IDS.MANUAL_DRILLING,
                    face: "A",
                    x: 40,
                    y: 50,
                    columns: 3,
                    rows: 2,
                    stepX: 32,
                    stepY: 64,
                    depth: 12,
                    diameter: 5
                }] }
            }
        });

        expect(result.code).toContain('XBO X=40 Y=50 Z=12 R=3 x=32 D=5 N="P"');
        expect(result.code).toContain('XBO X=40 Y=114 Z=12 R=3 x=32 D=5 N="P"');
    });

    it("keeps the current milling coordinate when Y mirroring is disabled", () => {
        const result = generateCncMachineCode({
            ...instance,
            configuration: {
                ...instance.configuration,
                flipYAxis: false
            }
        }, {
            part: {
                PID: "MILL-1",
                L: 450,
                B: 695,
                T: 20,
                CNC: {
                    operations: [
                        { id: "start", kind: MACHINING_KINDS.MILL_PATH, intentId: MACHINING_INTENT_IDS.BACK_RABBET, motion: "rapid", face: "A", target: { x: 0, y: 12, z: 9 } },
                        { id: "line", kind: MACHINING_KINDS.MILL_PATH, intentId: MACHINING_INTENT_IDS.BACK_RABBET, motion: "linear", face: "A", target: { x: 450, z: 9 } }
                    ]
                }
            }
        });

        expect(result.code).toContain("C=0\r\nXG0 X=0 Y=12 Z=9 T=114\r\nXL2P X=450 Y=12 Z=9");
    });

    it("exports a configured hinge cup endpoint as an XBO single drill", () => {
        const result = generateCncMachineCode(instance, {
            part: {
                PID: "hinge-cup",
                L: 450,
                B: 695,
                T: 20,
                CNC: { operations: [{ id: "hinge-cup", kind: MACHINING_KINDS.DRILL_POINT, intentId: MACHINING_INTENT_IDS.FRONT_HINGE_CUP, face: "A", x: 100, y: 22.5, diameter: 35, depth: 13 }] }
            }
        });

        expect(result.supported).toBe(true);
        expect(result.code).toContain('XBO X=100 Y=672.5 Z=13 R=1 D=35 N="P"');
    });

    it("uses the tool database and delegates radius correction to native Xilog C commands", () => {
        const result = generateCncMachineCode({
            ...instance,
            configuration: {
                ...instance.configuration,
                flipYAxis: false,
                toolDatabase: [{ id: "router-12", name: "Router", category: "milling", diameter: 12, toolNumber: 77 }]
            }
        }, {
            part: {
                PID: "MANUAL-COMP",
                L: 300,
                B: 200,
                T: 19,
                CNC: { operations: [{
                    id: "manual-line",
                    kind: MACHINING_KINDS.MILL_PATH,
                    intentId: MACHINING_INTENT_IDS.MANUAL_MILLING,
                    motion: "linear",
                    face: "A",
                    start: { x: 10, y: 20, z: 8 },
                    target: { x: 110, y: 20, z: 8 },
                    compensation: "left",
                    toolId: "router-12"
                }] }
            }
        });

        expect(result.supported).toBe(true);
        expect(result.code).toContain("C=2\r\nXG0 X=10 Y=20 Z=8 T=77\r\nXL2P X=110 Y=20 Z=8");
    });

    it("approaches the explicitly programmed start of an isolated milling line with G0", () => {
        const result = generateCncMachineCode({
            ...instance,
            configuration: { ...instance.configuration, flipYAxis: false }
        }, {
            part: {
                PID: "MANUAL-START",
                L: 300,
                B: 200,
                T: 19,
                CNC: { operations: [{
                    id: "manual-line",
                    kind: MACHINING_KINDS.MILL_PATH,
                    intentId: MACHINING_INTENT_IDS.MANUAL_MILLING,
                    motion: "linear",
                    face: "A",
                    start: { x: 25, y: 30, z: 8 },
                    target: { x: 125, y: 30, z: 8 },
                    compensation: "center",
                    toolId: "router-8"
                }] }
            }
        });

        expect(result.code).toContain("C=0\r\nXG0 X=25 Y=30 Z=8 T=114\r\nXL2P X=125 Y=30 Z=8");
    });

    it("emits a native XGFIL between two lines with only one XG0 for the path", () => {
        const result = generateCncMachineCode({
            ...instance,
            configuration: { ...instance.configuration, flipYAxis: false }
        }, {
            part: {
                PID: "MANUAL-ARC",
                L: 300,
                B: 200,
                T: 19,
                CNC: { operations: [
                    {
                        id: "manual-start",
                        kind: MACHINING_KINDS.MILL_PATH,
                        intentId: MACHINING_INTENT_IDS.MANUAL_MILLING,
                        motion: "rapid",
                        face: "A",
                        target: { x: 20, y: 100, z: 8 },
                        compensation: "center",
                        toolId: "router-8"
                    },
                    {
                        id: "manual-line-1",
                        kind: MACHINING_KINDS.MILL_PATH,
                        intentId: MACHINING_INTENT_IDS.MANUAL_MILLING,
                        motion: "linear",
                        face: "A",
                        start: { x: 20, y: 100, z: 8 },
                        target: { x: 90, y: 100, z: 8 },
                        compensation: "center",
                        toolId: "router-8",
                        feed: 5
                    },
                    {
                        id: "manual-arc",
                        kind: MACHINING_KINDS.MILL_PATH,
                        intentId: MACHINING_INTENT_IDS.MANUAL_MILLING,
                        motion: "arc",
                        face: "A",
                        start: { x: 90, y: 100, z: 8 },
                        target: { x: 100, y: 110, z: 8 },
                        center: { x: 90, y: 110, z: 8 },
                        radius: 10,
                        direction: "clockwise",
                        compensation: "center",
                        toolId: "router-8"
                    },
                    {
                        id: "manual-line-2",
                        kind: MACHINING_KINDS.MILL_PATH,
                        intentId: MACHINING_INTENT_IDS.MANUAL_MILLING,
                        motion: "linear",
                        face: "A",
                        start: { x: 100, y: 110, z: 8 },
                        target: { x: 100, y: 180, z: 8 },
                        compensation: "center",
                        toolId: "router-8",
                        feed: 5
                    }
                ] }
            }
        });

        expect(result.supported).toBe(true);
        expect(result.code).toContain([
            "C=0",
            "XG0 X=20 Y=100 Z=8 T=114",
            "XL2P X=100 Y=100 Z=8 V=5",
            "XGFIL r=10",
            "XL2P X=100 Y=180 Z=8 V=5"
        ].join("\r\n"));
        expect(result.code.match(/XG0/g)).toHaveLength(1);
    });

    it("blocks an operation kind that does not match the assigned endpoint", () => {
        const result = generateCncMachineCode(instance, {
            part: {
                PID: "unsafe",
                L: 450,
                B: 695,
                T: 20,
                CNC: { operations: [{ id: "unknown", kind: MACHINING_KINDS.MILL_GROOVE, intentId: MACHINING_INTENT_IDS.FRONT_HINGE_CUP, face: "A", start: { x: 0, y: 0, z: 13 }, end: { x: 10, y: 0, z: 13 }, width: 35 }] }
            }
        });

        expect(result.supported).toBe(false);
        expect(result.code).toBeNull();
        expect(result.diagnostics).toContainEqual(expect.objectContaining({
            level: "error",
            code: "UNSUPPORTED_MACHINING_ENDPOINT",
            operationId: "unknown"
        }));
    });
});
